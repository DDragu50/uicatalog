// llms.mjs
//
// AI ENTRY FILES ("npm run llms"). Writes two files at the library root, the common convention for AI tools (llmstxt.org):
//   llms.txt       an index: what UI Catalog is, the documents to read first, then one line per component (name, its
//                  README and the first sentence of its Overview);
//   llms-full.txt  everything in one file: AGENTS.md, the how-to guide, then every component README.
// Run it after a README or one of these documents changes; `npm run release` writes both files again, so a release
// always ships them up to date. `node tools/llms.mjs --check` only reports whether they are.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, listComponents, readComponentFile } from './lib.mjs';

const GUIDES = [ 'AGENTS.md', 'source/components-js/how-to-use-the-framework.md', 'source/components-js/how-to-build-a-design-system.md', 'source/components-js/framework-component-development-guidelines.md' ];

// Returns the first sentence: up to the first . ! or ? followed by a space or the end, not counting abbreviations
// (e.g., i.e., etc.) or a full stop inside parentheses (the same rule as the showcase catalog).
function firstSentence( text )
{
    const ends = /[.!?](?=\s|$)/g;
    let match;
    while ( ( match = ends.exec(text) ) )
    {
        const candidate = text.slice(0,match.index + 1);
        const open = ( candidate.match(/\(/g) ?? [] ).length - ( candidate.match(/\)/g) ?? [] ).length;
        if ( open <= 0 && !/\b(e\.g|i\.e|etc|vs)\.$/i.test(candidate) ) { return candidate; }
    }
    return text;
}

// Returns the display name (# heading) and the first sentence of "### Overview" of a README.
function summaryOf( readme )
{
    const lines = readme.replace(/\r/g,'').split('\n');
    const name = ( lines.find(line => /^#\s+/.test(line)) ?? '' ).replace(/^#\s+/,'').trim();
    const start = lines.findIndex(line => /^###\s+Overview\s*$/.test(line));
    const paragraph = start < 0 ? '' : ( lines.slice(start + 1).find(line => line.trim() && !line.startsWith('#')) ?? '' );
    const plain = paragraph.replace(/`([^`]+)`/g,'$1').replace(/\*\*([^*]+)\*\*/g,'$1').replace(/<!--.*?-->/g,'').trim();
    return { name, sentence:firstSentence(plain) };
}

// Builds both files' text.
export function buildLlmsFiles()
{
    const names = listComponents();
    const index = [
        '# UI Catalog', '',
        '> Plain JavaScript components that AI tools configure, not rewrite: the same behaviour on every screen. Thirty components (ES modules and CSS, no framework, no build step), each with a README contract whose every requirement has a test case.', '',
        'Read AGENTS.md first: its rules win over everything else. Import only from each component\'s xIndex.js; configure through options, texts and callbacks; never change the component files.', '',
        '## Read first', '',
        '- [AGENTS.md](AGENTS.md): rules, quick reference, a table for choosing components',
        '- [How to use the framework](source/components-js/how-to-use-the-framework.md): loading, rendering, callbacks, forms, React/Vue/Svelte',
        '- [How to build a design system](source/components-js/how-to-build-a-design-system.md): adapting the tokens to a brand',
        '- [Component development guidelines](source/components-js/framework-component-development-guidelines.md): creating or changing a component', '',
        '## Components', '',
        ...names.map(name => { const { name:title, sentence } = summaryOf(readComponentFile(name,'README.md')); return `- [${title || name}](source/components-js/${name}/${name}README.md): ${sentence}`; }), '',
        '## Optional', '',
        '- [llms-full.txt](llms-full.txt): all of the above in one file',
        '- [DEPENDENCIES.md](DEPENDENCIES.md): browsers, fonts, icons and tools', ''
    ].join('\n');
    const part = ( title, text ) => `\n\n<!-- ===== ${title} ===== -->\n\n${text.trim()}\n`;
    const full = '# UI Catalog — full documentation for AI tools\n\nGenerated by `npm run llms` from the files named in each section heading.'
        + GUIDES.map(file => part(file,readFileSync(join(ROOT,file),'utf8'))).join('')
        + names.map(name => part(`source/components-js/${name}/${name}README.md`,readComponentFile(name,'README.md'))).join('');
    return { index, full };
}

// Writes the files, or (with --check) only reports whether they are up to date; returns true when they are.
export function writeLlmsFiles( check = false )
{
    const { index, full } = buildLlmsFiles();
    const files = [ [ 'llms.txt', index ], [ 'llms-full.txt', full ] ];
    const stale = files.filter(( [ file, text ] ) => { try { return readFileSync(join(ROOT,file),'utf8') !== text; } catch { return true; } });
    if ( check ) { stale.forEach(( [ file ] ) => console.log(`  ${file} is out of date (run npm run llms)`)); return stale.length === 0; }
    files.forEach(( [ file, text ] ) => writeFileSync(join(ROOT,file),text));
    console.log(`Written: llms.txt (${index.split('\n').length} lines), llms-full.txt (${Math.round(full.length / 1024)} kB)`);
    return true;
}

if ( import.meta.url === pathToFileURL(process.argv[1]).href ) { process.exitCode = writeLlmsFiles(process.argv.includes('--check')) ? 0 : 1; }
